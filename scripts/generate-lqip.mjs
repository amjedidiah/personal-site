// Blurred previews shown while project images load (src/data/image-placeholders.ts).
// Covers every project whose record has an `image`; rerun after adding or
// replacing one: `node scripts/generate-lqip.mjs`.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const projectsDir = fileURLToPath(new URL('../src/content/projects/', import.meta.url));
const placeholders = {};

for (const file of (await readdir(projectsDir)).filter((name) => name.endsWith('.md')).sort()) {
  const frontMatter = /^---\n([\s\S]*?)\n---/.exec(await readFile(path.join(projectsDir, file), 'utf8'))?.[1] ?? '';
  const image = /^image:\s*"([^"]+)"/m.exec(frontMatter)?.[1];
  if (!image) continue;
  const preview = await sharp(path.resolve(projectsDir, image))
    .resize({ width: 36 })
    .blur(2)
    .webp({ quality: 30, effort: 4 })
    .toBuffer();
  placeholders[file.replace(/\.md$/, '')] = `data:image/webp;base64,${preview.toString('base64')}`;
}

const output = `// Generated by scripts/generate-lqip.mjs.\nexport const imagePlaceholders: Record<string, string> = ${JSON.stringify(placeholders, null, 2)};\n`;
await writeFile(new URL('../src/data/image-placeholders.ts', import.meta.url), output);
console.log(`Placeholders for ${Object.keys(placeholders).length} projects.`);
