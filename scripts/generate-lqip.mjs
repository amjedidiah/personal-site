import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const sources = {
  ajoflow: new URL('../src/assets/projects/ajoflow-dashboard.webp', import.meta.url),
  gwela: new URL('../src/assets/projects/gwela-product.webp', import.meta.url),
};

const placeholders = {};

for (const [name, source] of Object.entries(sources)) {
  const preview = await sharp(fileURLToPath(source))
    .resize({ width: 36 })
    .blur(2)
    .webp({ quality: 30, effort: 4 })
    .toBuffer();
  placeholders[name] = `data:image/webp;base64,${preview.toString('base64')}`;
}

const output = `// Generated by scripts/generate-lqip.mjs.\nexport const imagePlaceholders: Record<string, string> = ${JSON.stringify(placeholders, null, 2)};\n`;
await writeFile(new URL('../src/data/image-placeholders.ts', import.meta.url), output);
